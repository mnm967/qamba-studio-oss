/** The template as the worker reads it. A placeholder template is not valid
 *  JSON until its handler substitutes, so this can fail — the caller only
 *  offers the button on `format === "api"`, which already excludes those. */
function apiOf(raw: string): ApiGraph | null {
  try {
    const g = JSON.parse(raw) as Record<string, unknown>;
    return Object.fromEntries(
      Object.entries(g).filter(([k]) => !k.startsWith("_"))) as ApiGraph;
  } catch { return null; }
}

/** A node's inputs, with links rendered as the node they come from. Literals
 *  are what resolve() overwrites, so they are worth seeing next to the
 *  contract that says whether it will. */
function inputSummary(n: WorkflowNode): string {
  const parts: string[] = [];
  for (const [k, v] of Object.entries(n.inputs)) {
    if (Array.isArray(v) && v.length === 2 && typeof v[0] === "string") parts.push(`${k}→#${v[0]}`);
    else if (typeof v === "string") parts.push(`${k}=${v.length > 34 ? `${v.slice(0, 33)}…` : v}`);
    else if (typeof v === "number" || typeof v === "boolean") parts.push(`${k}=${v}`);
    else parts.push(k);
  }
  return parts.join("  ");
}

