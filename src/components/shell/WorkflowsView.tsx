/** "3 minutes ago", for a list whose whole question is what changed last. */
function ago(ms: number): string {
  const s = Math.max(0, Math.round((Date.now() - ms) / 1000));
  if (s < 45) return "just now";
  const m = Math.round(s / 60);
  if (m < 60) return `${m}m ago`;
  const h = Math.round(m / 60);
  return h < 36 ? `${h}h ago` : `${Math.round(h / 24)}d ago`;
}

/**
 * A workflow sitting in ComfyUI, and the way back in.
 *
 * THE RETURN TRIP LANDS AS A `custom_workflows` ROW, NEVER AS AN EDIT TO A
 * TEMPLATE, and that is the whole shape of this feature rather than a
 * convenience: `resolve.py` parameterises the bundled templates by matching
 * `class_type`, which is safe only on graphs this repo wrote. An edited
 * template would still render and would silently stop taking the prompt, the
 * references or the LoRA stack — the failure this codebase keeps naming. A
 * user graph is driven by TAGGED SLOTS instead, which is what an import
 * produces and what both runners already know how to execute.
 */
function SavedInComfyDetail({ w, onImported }: {
  w: StagedWorkflow;
  onImported: (id: string) => void;
}) {
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<string | null>(null);
  const [note, setNote] = useState<string | null>(null);

  const go = async () => {
    setBusy(true); setErr(null); setNote(null);
    try {
      const r = await importFromComfy(w.file);
      setNote(r.replaced
        ? `Updated "${r.row.name}" — same row, so anything already pointing at it still resolves.`
        : `Imported as "${r.row.name}".`);
      onImported(r.row.id);
    } catch (e) {
      setErr(e instanceof Error ? e.message : String(e));
    } finally { setBusy(false); }
  };

  return (
    <div className="ws-card ns-l1" style={{ borderRadius: 18 }}>
      <div style={{ display: "flex", alignItems: "center", gap: 8, flexWrap: "wrap" }}>
        <FileJson size={14} style={{ color: INK_MUTE }} />
        <span className="mono" style={{ fontSize: 13.5, fontWeight: 600 }}>
          {w.file.replace(/\.json$/, "")}
        </span>
        <Badge color={w.ours ? "#458de8" : "#aa5bde"}>
          {w.ours ? "sent from here" : "made in ComfyUI"}
        </Badge>
        <span className="mono" style={{ fontSize: 10.5, color: INK_MUTE }}>
          saved {ago(w.modified_ms)} · {(w.bytes / 1024).toFixed(1)}KB
        </span>
        <div style={{ flex: 1 }} />
        <button className="ws-primary" onClick={() => void go()} disabled={busy}>
          {busy ? "Importing…" : "Import into Qamba"}
        </button>
      </div>

      <p style={{ fontSize: 12.5, color: "#c7cddb", margin: "10px 0 0", maxWidth: 680 }}>
        This is ComfyUI's copy, in its own workflows folder. Importing converts it to the
        API format the workers execute, tags the slots the studio writes into (prompt, seed,
        size, start frame, output) and files it under <b>Imported</b> — where it can be
        picked in the composer and rendered in the cloud or on this machine.
      </p>
      <p style={{ fontSize: 12, color: INK_MUTE, margin: "8px 0 0", maxWidth: 680 }}>
        It never edits the template it may have come from. The bundled graphs are
        parameterised by node CLASS, which only holds for graphs this studio wrote — an
        edited one would keep rendering and quietly stop taking the prompt. An imported
        graph is driven by its tagged slots instead, which is why the round trip lands here.
      </p>

      {(note || err) && (
        <div style={{
          marginTop: 10, fontSize: 12, padding: "8px 10px", borderRadius: 10,
          color: err ? "#f0b9a4" : "#c7cddb",
          background: err ? "rgba(232,115,74,0.09)" : "rgba(255,255,255,0.035)",
          border: `1px solid ${err ? "rgba(232,115,74,0.28)" : "rgba(255,255,255,0.07)"}`,
        }}>{err ?? note}</div>
      )}
    </div>
  );
}

