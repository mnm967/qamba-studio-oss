// The Workflows view — what ComfyUI graph each model actually renders on.
//
// READ-ONLY, on purpose. Editing or importing a graph means executing
// user-authored nodes on the shared $3.36/hr pod, which is a different
// security posture than anything else in the app; this ships the half that
// answers the question ("which workflow runs for H3 i2v, and what does it
// let me control?") without taking that on.
//
// WHERE THE DATA COMES FROM. Both halves are bundled from the repo at build
// time — the templates via import.meta.glob and model_map.full.json directly —
// rather than read from the pod or the DB. Three reasons, in order:
//   * the browser cannot talk to ComfyUI (invariant #1), so the pod is not an
//     option for a page that has to work while the box is asleep;
//   * `model_catalog.local_files` is a MIRROR of model_map synced by
//     scripts/gen_model_catalog.py, while the worker reads the deployed copy
//     of model_map itself — so the file is the truth and the table is the copy;
//   * bundling both from one git tree makes them consistent by construction.
//     The pod gets the same tree through the B2 tarball, so what this page
//     shows is what the worker loads, as long as both are deployed from the
//     same commit. That caveat is printed on the page rather than assumed.
//
// It is React.lazy'd in Workspace, unlike its sibling views: the glob inlines
// ~240KB of template JSON, which has no business in the main bundle for a tab
// most accounts cannot see.
