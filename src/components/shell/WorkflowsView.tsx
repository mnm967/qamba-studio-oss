/**
 * Send this graph to ComfyUI's editor.
 *
 * It reports where the file LANDED rather than claiming the editor opened it,
 * because it did not: this frontend has no URL intent for a workflow, so what
 * happens is that the file appears in ComfyUI's own Workflows sidebar. Saying
 * "opened in ComfyUI" and leaving someone staring at their last graph is the
 * kind of small lie that makes a feature read as broken.
 */
function EditInComfyButton({ name, source }: {
  name: string;
  source: { ui?: UiGraph | null; api?: ApiGraph | null };
}) {
  const engine = useLocalEngine();
  const [busy, setBusy] = useState(false);
  const [done, setDone] = useState<
    { file: string; note: string; opened: boolean; kept: boolean } | null>(null);
  const [err, setErr] = useState<string | null>(null);
  if (!engine.desktop) return null;

  const go = async (fresh = false) => {
    setBusy(true); setErr(null); setDone(null);
    try {
      const r = await editInComfy(name, source, { fresh });
      // KEPT means ComfyUI already had an edited copy and we did not touch it.
      // Saying "converted from API format" there would describe a document
      // that is not the one on screen.
      if (r.kept) {
        setDone({
          file: r.file, opened: r.opened, kept: true,
          note: "your edited copy is what opened — nothing was overwritten",
        });
        return;
      }
      setDone({
        file: r.file, opened: r.opened, kept: false,
        note: r.unmapped.length
          ? `${r.unmapped.length} node type${r.unmapped.length > 1 ? "s" : ""} the engine `
            + `does not have (${r.unmapped.slice(0, 3).join(", ")}) kept their shape but not `
            + "their values — install the pack and send it again"
          : r.native ? "the author's own layout, staged as-is"
          : "converted from API format, so the layout is generated",
      });
    } catch (e) {
      setErr(e instanceof Error ? e.message : String(e));
    } finally { setBusy(false); }
  };

  return (
    <>
      <button className="ws-actbtn" onClick={() => void go(false)}
        disabled={busy || !engine.running}
        title={engine.running
          ? "Convert if needed, put it in ComfyUI's own workflow list, and open ComfyUI"
          : "Start your engine first — the widget order comes from the running ComfyUI"}
        style={{ display: "inline-flex", alignItems: "center", gap: 6, fontSize: 11.5 }}>
        <ExternalLink size={12} />{busy ? "Sending…" : "Edit in ComfyUI"}
      </button>
      {(done || err) && (
        <div style={{
          marginTop: 10, fontSize: 12, padding: "8px 10px", borderRadius: 10, width: "100%",
          color: err ? "#f0b9a4" : "#c7cddb",
          background: err ? "rgba(232,115,74,0.09)" : "rgba(255,255,255,0.035)",
          border: `1px solid ${err ? "rgba(232,115,74,0.28)" : "rgba(255,255,255,0.07)"}`,
        }}>
          {err ?? <>
            {done!.opened ? "Opened in ComfyUI as " : "Saved as "}
            <span className="mono">{done!.file}</span>
            {done!.opened
              ? <> — it is in the <b>Workflows</b> sidebar there too.</>
              : <> — open ComfyUI's <b>Workflows</b> sidebar (press{" "}
                  <span className="mono">w</span>) and click it.</>}
            <span style={{ color: INK_MUTE }}> {done!.note}.</span>
            {done!.kept && (
              <div style={{ marginTop: 8, display: "flex", gap: 8, alignItems: "center" }}>
                <span style={{ color: INK_MUTE, fontSize: 11.5 }}>
                  Import it from <b>In ComfyUI</b> to bring those changes back, or
                </span>
                <button className="ws-actbtn" onClick={() => void go(true)} disabled={busy}
                  title="Replace ComfyUI's copy with a fresh conversion — your edits there are lost"
                  style={{ fontSize: 11.5 }}>
                  Start over from this graph
                </button>
              </div>
            )}
          </>}
        </div>
      )}
    </>
  );
}

function CopyButton({ text, label }: { text: string; label: string }) {
  const [done, setDone] = useState(false);
  return (
    <button
      className="ws-actbtn"
      onClick={async () => {
        try {
          await navigator.clipboard.writeText(text);
          setDone(true);
          setTimeout(() => setDone(false), 1400);
        } catch { /* clipboard blocked — the raw JSON is on screen anyway */ }
      }}
      style={{ display: "inline-flex", alignItems: "center", gap: 6, fontSize: 11.5 }}
    >
      {done ? <Check size={12} /> : <Copy size={12} />}{done ? "Copied" : label}
    </button>
  );
}

/**
 * What a GENERATED map could not carry, in the generator's own words.
 *
 * Collapsed to one line, because this is the question you only ask once you
 * have noticed the tier looks thin — and thin is exactly how the desktop tier
 * looks (four reachable templates against the pod's twelve) until you read it.
 * `scripts/gen_desktop_model_map.mjs` records a reason for every entry it
 * drops; leaving that in a file nobody opens is what made "the desktop can't
 * render Krea 2" a mystery rather than a sentence.
 */
function MapReport({ prov }: { prov: MapProvenance }) {
  const [open, setOpen] = useState(false);
  const sections = useMemo(() => {
    const out = new Map<string, { key: string; why: string }[]>();
    for (const d of prov.dropped) {
      out.set(d.section, [...(out.get(d.section) ?? []), { key: d.key, why: d.why }]);
    }
    return [...out.entries()].sort((a, b) => a[0].localeCompare(b[0]));
  }, [prov]);

  const counts = [
    prov.dropped.length && `${prov.dropped.length} entries dropped`,
    prov.adaptersDropped.length && `${prov.adaptersDropped.length} adapter sets pruned`,
    prov.strippedKeys.length && `${prov.strippedKeys.length} keys stripped`,
  ].filter(Boolean).join(" · ");

  return (
    <div className="ws-card ns-l1" style={{ borderRadius: 14, padding: "10px 12px", marginBottom: 12 }}>
      <div style={{ display: "flex", alignItems: "center", gap: 8, flexWrap: "wrap" }}>
        <Layers size={13} style={{ color: INK_MUTE, flex: "none" }} />
        <span style={{ fontSize: 12.5 }}>
          This map is generated — <span style={{ color: INK_MUTE }}>{counts}</span>
        </span>
        <div style={{ flex: 1 }} />
        {/* The generator's own path is a repo detail and says nothing anyone
            reading this page can act on — the sentence beside it already
            carries the fact that matters, which is that the map is derived. */}
        <button className="ws-actbtn" onClick={() => setOpen((v) => !v)} style={{ fontSize: 11.5 }}>
          {open ? "Hide" : "What is missing"}
        </button>
      </div>

      {open && (
        <div style={{ marginTop: 10, display: "flex", flexDirection: "column", gap: 12 }}>
          {sections.map(([section, items]) => (
            <div key={section}>
              <div className="mono" style={{ fontSize: 10, color: INK_MUTE, marginBottom: 4 }}>
                {section.toUpperCase()} · {items.length}
              </div>
              {items.map((d) => (
                <div key={d.key} style={{ display: "flex", gap: 8, padding: "2px 0", fontSize: 11.5 }}>
                  <span className="mono" style={{ width: 176, flex: "none", color: "#eaeef6" }}>
                    {d.key}
                  </span>
                  <span style={{ color: INK_MUTE, minWidth: 0 }}>{d.why}</span>
                </div>
              ))}
            </div>
          ))}

          {prov.adaptersDropped.length > 0 && (
            <div>
              <div className="mono" style={{ fontSize: 10, color: INK_MUTE, marginBottom: 4 }}>
                ADAPTERS PRUNED — the file is not fetchable here, so the key is dropped
                rather than resolved to nothing
              </div>
              {prov.adaptersDropped.map((a) => (
                <div key={a.model} style={{ display: "flex", gap: 8, padding: "3px 0", flexWrap: "wrap" }}>
                  <span className="mono" style={{ width: 176, flex: "none", fontSize: 11.5 }}>
                    {a.model}
                  </span>
                  <span style={{ display: "flex", gap: 4, flexWrap: "wrap" }}>
                    {a.loras.map((l) => <Badge key={l} color={INK_MUTE}>{l}</Badge>)}
                  </span>
                </div>
              ))}
            </div>
          )}

          {prov.strippedKeys.length > 0 && (
            <div>
              <div className="mono" style={{ fontSize: 10, color: INK_MUTE, marginBottom: 4 }}>
                KEYS STRIPPED FROM EVERY ENTRY
              </div>
              {prov.strippedKeys.map((k) => (
                <div key={k.key} style={{ display: "flex", gap: 8, padding: "2px 0", fontSize: 11.5 }}>
                  <span className="mono" style={{ width: 176, flex: "none", color: "#eaeef6" }}>
                    {k.key}
                  </span>
                  <span style={{ color: INK_MUTE, minWidth: 0 }}>{k.why}</span>
                </div>
              ))}
            </div>
          )}

          {prov.from && (
            <div className="mono" style={{ fontSize: 10.5, color: INK_MUTE }}>
              derived from {prov.from}
            </div>
          )}
        </div>
      )}
    </div>
  );
}

